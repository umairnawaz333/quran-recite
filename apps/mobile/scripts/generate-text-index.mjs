// Writes a static require map for Metro. Each entry is a thunk, so a surah's
// JSON is parsed on first access rather than all 114 at startup — the bundle
// carries 9.2 MB either way, but the parse cost is paid per surah opened.
import { readdirSync, writeFileSync } from 'node:fs';
import path from 'node:path';

const dataDir = path.resolve(import.meta.dirname, '../../../packages/quran-data/text');
const ids = readdirSync(dataDir)
  .filter(f => f.endsWith('.json'))
  .map(f => Number(f.replace('.json', '')))
  .sort((a, b) => a - b);

const entries = ids
  .map(id => `  ${id}: () => require('@quran/data/text/${id}.json') as SurahText,`)
  .join('\n');

writeFileSync(
  path.resolve(import.meta.dirname, '../src/data/textIndex.generated.ts'),
  `// GENERATED by scripts/generate-text-index.mjs — do not edit.\n` +
    `import type { SurahText } from '@quran/core';\n\n` +
    `export const textLoaders: Record<number, () => SurahText> = {\n${entries}\n};\n`,
  'utf8',
);
console.log(`wrote ${ids.length} entries`);
